"""Record every version of the shipped config files, so the 1.3 → 1.4 migration can tell an untouched
copy of a default (dropped: the user gets the current default) from the user's own file (kept).

Scans the git history of one or more repositories and writes the content hashes (see
``pitchcontrol.config.loader.content_hash``: whitespace, key order and the app version don't count)
into ``backend/src/pitchcontrol/config/shipped_history.py``, keeping the hashes already there.

    python tools/shipped_config_history.py                       # this repo, config/
    python tools/shipped_config_history.py --repo ../PitchPlease --prefix pitch_control/config

Run it as part of every release that changes a default (see "Releasing a version" in docs/development.md).
"""

from __future__ import annotations

import argparse
import ast
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend" / "src"))

from pitchcontrol.config.loader import content_hash  # noqa: E402

OUT = ROOT / "backend" / "src" / "pitchcontrol" / "config" / "shipped_history.py"


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", *args], cwd=repo, capture_output=True, text=True, check=True, encoding="utf-8").stdout


def scan(repo: Path, prefix: str) -> dict[str, set[str]]:
    prefix = prefix.rstrip("/") + "/"
    found: dict[str, set[str]] = {}
    for commit in git(repo, "rev-list", "--all", "--", prefix).split():
        for line in git(repo, "ls-tree", "-r", commit, "--", prefix).splitlines():
            meta, path = line.split("\t", 1)
            rel = path[len(prefix) :]
            if not rel.endswith(".json") or rel.split("/")[0] == "state":
                continue
            blob = meta.split()[2]
            try:
                data = json.loads(git(repo, "cat-file", "blob", blob))
            except ValueError:
                continue
            found.setdefault(rel, set()).add(content_hash(data))
    return found


def existing() -> dict[str, set[str]]:
    if not OUT.exists():
        return {}
    tree = ast.parse(OUT.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == "_HASHES":
            return {k: set(v) for k, v in ast.literal_eval(node.value).items()}
    return {}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--repo", type=Path, default=ROOT)
    parser.add_argument("--prefix", default="config")
    args = parser.parse_args()

    merged = existing()
    for rel, hashes in scan(args.repo.resolve(), args.prefix).items():
        merged.setdefault(rel, set()).update(hashes)

    lines = [
        '"""Content hashes of every config file version the app has shipped (generated by',
        "tools/shipped_config_history.py; don't edit by hand). Path relative to the config folder -> hashes.\"\"\"",
        "",
        "_HASHES: dict[str, list[str]] = {",
    ]
    for rel in sorted(merged):
        lines.append(f"    {rel!r}: {sorted(merged[rel])!r},")
    lines += ["}", "", "SHIPPED: dict[str, frozenset[str]] = {k: frozenset(v) for k, v in _HASHES.items()}"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT}: {len(merged)} files, {sum(len(v) for v in merged.values())} versions")


if __name__ == "__main__":
    main()
